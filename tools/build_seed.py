#!/usr/bin/env python3
"""Build NodeTaxi/data.lua from a GatherMate2 data package.

Usage:
    python3 tools/build_seed.py /path/to/GatherMate2_Data/Forever \
        [--version gathermate2-forever-2026-11-08+scans]

The source files are plain Lua assignments:

    GatherMateData2HerbDB = {
        [1411] = {
            [3570284000] = 401,   -- coordinate key -> node id
        },
    }

We keep both the coordinate key and the node id: the key gives the position,
the id selects a resource-specific icon from tools/node_icons.json.
"""
import argparse
import json
import re
import sys
from pathlib import Path

ZONE_RE = re.compile(r"^\s*\[(\d+)\]\s*=\s*\{\s*$")
NODE_RE = re.compile(r"^\s*\[(\d+)\]\s*=\s*(\d+)\s*,?\s*$")
ICON_ROOT = "Interface\\AddOns\\NodeTaxi\\Media\\"


def parse(path):
    zones = {}
    current = None
    for line in path.read_text(encoding="utf-8").splitlines():
        zone_match = ZONE_RE.match(line)
        if zone_match:
            current = int(zone_match.group(1))
            zones.setdefault(current, [])
            continue
        if current is not None:
            node_match = NODE_RE.match(line)
            if node_match:
                zones[current].append((int(node_match.group(1)), int(node_match.group(2))))
            elif line.strip() == "},":
                current = None
    return zones


def valid_key(key):
    x = (key // 1_000_000) / 10_000
    y = ((key % 1_000_000) // 100) / 10_000
    return 0 <= x <= 1 and 0 <= y <= 1


def write_zones(out, name, zones, indent="    "):
    out.write(f"{indent}{name} = {{\n")
    for zone in sorted(zones):
        pairs = sorted(zones[zone])
        keys = ",".join(str(key) for key, _ in pairs)
        ids = ",".join(str(node_id) for _, node_id in pairs)
        out.write(f"{indent}    [{zone}] = {{\n")
        out.write(f"{indent}        keys = {{\n")
        for i in range(0, len(keys.split(",")) if keys else 0, 10):
            chunk = keys.split(",")[i:i + 10]
            out.write(f"{indent}            " + ",".join(chunk) + ",\n")
        out.write(f"{indent}        }},\n")
        out.write(f"{indent}        ids = {{ {ids} }},\n")
        out.write(f"{indent}    }},\n")
    out.write(f"{indent}}},\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("data_dir", type=Path)
    parser.add_argument("--version", default="gathermate2-forever-2026-11-08+scans")
    parser.add_argument("--out", type=Path, default=Path(__file__).resolve().parent.parent / "data.lua")
    parser.add_argument("--extra", type=Path,
        default=Path(__file__).resolve().parent / "extra_nodes.json")
    args = parser.parse_args()

    herb = parse(args.data_dir / "HerbalismData.lua")
    mine = parse(args.data_dir / "MiningData.lua")
    extra_count = 0
    if args.extra.exists():
        extras = json.loads(args.extra.read_text())
        for entry in extras:
            target = mine if entry.get("kind") == "ore" else herb
            zone = target.setdefault(int(entry["map"]), [])
            pair = (int(entry["key"]), int(entry["id"]))
            if pair not in zone:
                zone.append(pair)
                extra_count += 1
    icon_file = Path(__file__).resolve().parent / "node_icons.json"
    icons = json.loads(icon_file.read_text()) if icon_file.exists() else {}

    used_ids = set()
    for label, zones, expect in (
        ("herbs", herb, "HerbalismData.lua"),
        ("mines", mine, "MiningData.lua"),
    ):
        nodes = sum(len(v) for v in zones.values())
        print(f"{label}: {nodes} nodes in {len(zones)} zones ({expect})")
        bad = [k for z in zones.values() for k, _ in z if not valid_key(k)]
        if bad:
            print(f"ERROR: {len(bad)} invalid keys, e.g. {bad[:5]}", file=sys.stderr)
            return 1
        if nodes == 0:
            print(f"ERROR: no nodes parsed from {expect}", file=sys.stderr)
            return 1
        for zone in zones.values():
            for _, node_id in zone:
                used_ids.add(node_id)

    with args.out.open("w", encoding="utf-8") as out:
        out.write("-- NodeTaxi baked Forever node seed. Generated by tools/build_seed.py; do not edit.\n")
        out.write(f"-- Source: \"GatherMate2 Data Wowhead classic\" (Forever tables, {args.version}),\n")
        out.write("-- by Marrtin, based on Spinx's classic data, coordinates from Wowhead.\n")
        out.write("-- Extra nodes: NodeTaxi scanned/imported nodes in tools/extra_nodes.json.\n")
        out.write("-- Node art: GatherMate2 Artwork (Nevcairiel), bundled under Media/.\n")
        out.write("local ADDON_NAME, ns = ...\n")
        out.write("ns.SeedData = {\n")
        out.write(f'    version = "{args.version}",\n')
        out.write("    icons = {\n")
        for node_id in sorted(used_ids):
            path = icons.get(str(node_id))
            if path:
                full = (ICON_ROOT + path.replace("/", "\\")).replace("\\", "\\\\")
                out.write(f'        [{node_id}] = "{full}",\n')
        out.write("    },\n")
        write_zones(out, "herbs", herb)
        write_zones(out, "mines", mine)
        out.write("}\n")

    print(f"merged {extra_count} extra node(s) from {args.extra}")
    print(f"wrote {args.out} ({args.out.stat().st_size / 1024:.0f} KiB), {len(used_ids)} node ids")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
