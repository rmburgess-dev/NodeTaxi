#!/usr/bin/env python3
"""Union a newer Classic node package into an existing data.lua snapshot."""
import argparse, json, re, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_seed import parse, write_zones, valid_key

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent

def parse_generated(path):
    text = path.read_text()
    result = {}
    for kind in ("herbs", "mines"):
        marker = f"    {kind} = {{"
        start = text.index(marker)
        if kind == "herbs":
            end = text.index("    mines = {", start)
        else:
            end = text.index("\n}", start)
        block = text[start:end]
        zones = {}
        for match in re.finditer(
                r"\[(\d+)\] = \{\s*keys = \{(.*?)\},\s*ids = \{(.*?)\},\s*\}",
                block, re.S):
            zone = int(match.group(1))
            keys = [int(x) for x in re.findall(r"\d+", match.group(2))]
            ids = [int(x) for x in re.findall(r"\d+", match.group(3))]
            if len(keys) != len(ids):
                raise SystemExit(f"unaligned zone {zone} in {kind}")
            zones[zone] = list(zip(keys, ids))
        result[kind] = zones
    return result

def merge_into(base, addition):
    added = updated = 0
    for zone, pairs in addition.items():
        target = base.setdefault(zone, [])
        known = dict(target)
        for key, node_id in pairs:
            if key in known:
                index = next(i for i, (k, _) in enumerate(target) if k == key)
                if target[index][1] != node_id:
                    target[index] = (key, node_id)
                    updated += 1
            else:
                target.append((key, node_id))
                added += 1
    return added, updated

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("base", type=Path)
    parser.add_argument("package", type=Path)
    parser.add_argument("--version", default="classic-2026-11-16+scans")
    parser.add_argument("--out", type=Path, default=ROOT / "data.lua")
    args = parser.parse_args()

    base = parse_generated(args.base)
    new = {
        "herbs": parse(args.package / "HerbalismData.lua"),
        "mines": parse(args.package / "MiningData.lua"),
    }
    for kind in ("herbs", "mines"):
        for zone, pairs in new[kind].items():
            bad = [key for key, _ in pairs if not valid_key(key)]
            if bad:
                raise SystemExit(f"invalid keys in {kind} {zone}: {bad[:3]}")
        added, updated = merge_into(base[kind], new[kind])
        total = sum(len(v) for v in base[kind].values())
        print(f"{kind}: merged {added} new, updated {updated} ids, total {total}")

    icons = json.loads((HERE / "node_icons.json").read_text())
    used = {node_id for zones in base.values() for pairs in zones.values() for _, node_id in pairs}
    with args.out.open("w", encoding="utf-8") as out:
        out.write("-- NodeTaxi baked node seed. Generated by tools/build_seed.py; do not edit.\n")
        out.write(f"-- Source: public Classic node coordinates ({args.version}), standardized by NodeTaxi.\n")
        out.write("-- Artwork: resolved at runtime from Blizzard item icons via GetItemIcon.\n")
        out.write("local ADDON_NAME, ns = ...\n")
        out.write("ns.SeedData = {\n")
        out.write(f'    version = "{args.version}",\n')
        out.write("    icons = {\n")
        for node_id in sorted(used):
            path = icons.get(str(node_id))
            if path:
                out.write(f'        [{node_id}] = "{path}",\n')
        out.write("    },\n")
        write_zones(out, "herbs", base["herbs"])
        write_zones(out, "mines", base["mines"])
        out.write("}\n")
    print("wrote", args.out)

if __name__ == "__main__":
    main()
